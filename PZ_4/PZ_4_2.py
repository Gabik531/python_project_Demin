#Вариант 11 Данно целое число N (> 1). Найти наименьшее целое число K, при которм выполняется неравенство 3^K > N.

while True:
    try:
        n = int(input("Ввелите целое число N (N > 1): "))
        if n > 1:
            break
        print("Число должно быть больше 1!")
    except ValueError:
        print("Неправельно ввели! ")
        
k = 0 
p = 1 

while p <= n:
    p = p * 3   
    k = k + 1   
print("k =", k)