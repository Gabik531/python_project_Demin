# Вариант 11. Задание 3.
# Дан список размера N. Осуществить сдвиг элементов списка
# влево на одну позицию с потерей первого элемента.
# Последний элемент полученного списка положить равным 0.


import random

try:
    n = int(input('Введите размер списка: '))

    if n > 0:
        # Формирование исходного списка.
        a = []
        for i in range(n):
            a.append(random.randint(-100, 100))

        print('Исходный список:', a)

        # Сдвиг элементов влево на одну позицию.
        for i in range(n - 1):
            a[i] = a[i + 1]

        # Замена последнего элемента нулём.
        a[n - 1] = 0
        print('Результирующий список:', a)
    else:
        print('Размер списка должен быть положительным.')
except ValueError:
    print('Ошибка: необходимо ввести целое число.')
