# Вариант 11. Задание 1.
# Дан список A размера N (N — чётное число).
# Вывести элементы с чётными номерами в порядке возрастания
# номеров. Условный оператор не использовать.

import random

# Формирование списка чётного размера.
n = int(input('Введите чётный размер списка: '))
a = []
for i in range(n):
    a.append(random.randint(-100, 100))

print('Исходный список:', a)

# Номерам 2, 4, 6 соответствуют индексы 1, 3, 5.
b = []
for i in range(1, n, 2):
    b.append(a[i])

print('Результирующий список:', b)
