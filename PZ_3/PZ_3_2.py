#Вариант 11  Дано целое число, лежащее в диапозоне 1-999. Вывести его строку-
#описание вида"четное двузначное число", "неечтное трехначное число" и т.д

k = input("Введите число от 1 до 999: ")
while type(k) != int:
    try:
        k = int(k)
        if not 1 <= k <= 999:
            print("число вне диапозона!")
            k = input("Введите число от 1 до 999: ")
    except ValueError:
        print("Неправильно ввели!")
        k = input("Введите число от 1 до 999: ")
if k % 2 == 0:
    parity = "Четное"
else:
    parity = "Нечетное"
if k < 10:
    size = "Однозначное"
elif k < 100:
    size = "Двузначное"
else:
    size = "Трехзначное"
print(parity, size, "Число")

