 # Варинат 11 Даны два целых числа: А, В. Проверить истинность высказывания: "Числа А и В имеют одинаковою четность"
a = input("Введите целое число А:")
b = input("Введите целое число В:")
while type(a) != int:
    try:
        a = int(a)
    except ValueError:
        print("Число не целое, введите заново")
        a = input("Введите целое число А:")
while type(b) != int:
    try:
        b = int(b)
    except ValueError:
        print("Число не целое, введите заново")
        b = input("Введите целое число В:")
if a % 2 == b % 2:
    print("Высказывание истинно")
else:
    print("Высказывание ложно")

