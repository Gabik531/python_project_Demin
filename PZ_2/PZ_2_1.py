# Дано двузначное число. Вывести вначале его левую цифру(десятки)
# а затем - его правую цифру(еденицы). Для нахождения десятков
# использовать операцию деления нацело, для нахождения едениц
# операцию взятия остатка от деления

while True:
    try:
        num = int(input("Введите двузначное число: "))
    except ValueError:
        print("Ошибка: введите целое число")
        continue
    if abs(num) < 10 or abs(num) > 99:
        print("Ошибка: число должно быть двузначным")
        continue
    break

num = abs(num)
des = num // 10
ed = num % 10
print("Десятки", des)
print("Еденицы", ed)
