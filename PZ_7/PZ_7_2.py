# Дана строка, содержащая полное имя файла.
# Выделить название первого каталога без символов «\».
# Если файл находится в корневом каталоге, вывести «\».



s = input('Введите полное имя файла: ')
print('Исходная строка:', s)

# Разделение пути по обратной косой черте.
parts = s.split('\\')

# Если после имени диска указан только файл, каталог корневой.
if len(parts) == 2:
    result = '\\'
elif len(parts) > 2:
    result = parts[1]
else:
    result = 'Ошибка: введите полный путь к файлу.'

print('Результирующая строка:', result)
